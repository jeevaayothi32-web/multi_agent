export function extractJson(text: string): string {
  // 1. Try to find markdown JSON code block first
  const codeBlockMatch = text.match(/```(?:json)?\s*([\s\S]*?)\s*```/i);
  if (codeBlockMatch) {
    return codeBlockMatch[1].trim();
  }

  // 2. Collect ALL {…} substrings from the text and return the longest valid-looking one
  const candidates: string[] = [];
  let depth = 0;
  let start = -1;

  for (let i = 0; i < text.length; i++) {
    if (text[i] === '{') {
      if (depth === 0) start = i;
      depth++;
    } else if (text[i] === '}') {
      depth--;
      if (depth === 0 && start !== -1) {
        candidates.push(text.substring(start, i + 1));
        start = -1;
      }
    }
  }

  // Return the longest candidate (most likely the full JSON object)
  if (candidates.length > 0) {
    return candidates.sort((a, b) => b.length - a.length)[0];
  }

  return text.trim();
}

export function cleanAndParseJson<T>(rawText: string): T {
  const extracted = extractJson(rawText);
  try {
    return JSON.parse(extracted) as T;
  } catch (e) {
    // Attempt standard fixes for JSON generated by LLMs
    const cleaned = extracted
      .replace(/,\s*([\]}])/g, '$1') // remove trailing commas
      .replace(/[\u0000-\u001F\u007F-\u009F]/g, '') // remove control characters
      .trim();

    try {
      return JSON.parse(cleaned) as T;
    } catch (innerError: any) {
      console.error('Failed to parse JSON even after cleaning:', innerError);
      throw new Error(`Invalid JSON format returned by agent: ${innerError.message}`);
    }
  }
}

export function calculateOverallScore(scores: {
  feasibility?: number;
  market?: number;
  technical?: number;
  innovation?: number;
  risk?: number;
  legal?: number;
}): number {
  const values = [
    scores.feasibility,
    scores.market,
    scores.technical,
    scores.innovation,
    scores.risk,
    scores.legal,
  ].filter((v): v is number => typeof v === 'number');

  if (values.length === 0) return 0;
  
  const sum = values.reduce((acc, val) => acc + val, 0);
  return Math.round(sum / values.length);
}

export function getVerdict(overallScore: number): 'High Potential' | 'Moderate Potential' | 'Needs Improvement' {
  if (overallScore >= 80) return 'High Potential';
  if (overallScore >= 60) return 'Moderate Potential';
  return 'Needs Improvement';
}

export function generateExplanation(results: AgentResultsMap): string {
  const agentsList = [
    { name: 'feasibility', label: 'practical feasibility', score: results.feasibility?.score },
    { name: 'market', label: 'market viability', score: results.market?.score },
    { name: 'technical', label: 'technical execution potential', score: results.technical?.score },
    { name: 'innovation', label: 'innovation uniqueness', score: results.innovation?.score },
    { name: 'risk', label: 'favorable risk profile', score: results.risk?.score },
    { name: 'legal', label: 'regulatory & compliance security', score: results.legal?.score },
  ];

  const validAgents = agentsList.filter(
    (a): a is { name: string; label: string; score: number } => typeof a.score === 'number'
  );

  if (validAgents.length === 0) {
    return 'No score data available to generate an explanation.';
  }

  const strengths = validAgents
    .filter((a) => a.score >= 75)
    .map((a) => a.label);

  const cautions = validAgents
    .filter((a) => a.score < 60)
    .map((a) => a.label);

  const moderate = validAgents
    .filter((a) => a.score >= 60 && a.score < 75)
    .map((a) => a.label);

  if (strengths.length > 0 && cautions.length > 0) {
    const strengthText = strengths.length === 1 ? strengths[0] : `${strengths.slice(0, -1).join(', ')} and ${strengths[strengths.length - 1]}`;
    const cautionText = cautions.length === 1 ? cautions[0] : `${cautions.slice(0, -1).join(', ')} and ${cautions[cautions.length - 1]}`;
    return `Your idea shows strong ${strengthText}, but concerns in ${cautionText} require further validation and planning.`;
  }

  if (strengths.length > 0 && cautions.length === 0) {
    const strengthText = strengths.length === 1 ? strengths[0] : `${strengths.slice(0, -1).join(', ')} and ${strengths[strengths.length - 1]}`;
    const modText = moderate.length > 0 ? ` with moderate performance in ${moderate.join(', ')}` : '';
    return `Your idea shows excellent potential overall, particularly in its ${strengthText}${modText}, and presents no major barriers to execution.`;
  }

  if (strengths.length === 0 && cautions.length > 0) {
    const cautionText = cautions.length === 1 ? cautions[0] : `${cautions.slice(0, -1).join(', ')} and ${cautions[cautions.length - 1]}`;
    return `This project requires significant refinement and planning, specifically addressing key vulnerabilities in ${cautionText}.`;
  }

  // All moderate
  return `The concept is moderately balanced across all parameters, showing solid baseline feasibility, market, and technical potential but lacking a standout competitive edge.`;
}

export function formatDate(timestampStr: string): string {
  try {
    const date = new Date(timestampStr);
    return date.toLocaleDateString(undefined, {
      year: 'numeric',
      month: 'short',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    });
  } catch (e) {
    return timestampStr;
  }
}
